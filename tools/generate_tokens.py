#!/usr/bin/env python3
"""Generate the frontend token layer from tokens/*.json.

Output is a generated artefact: ui/src/tokens/ is never hand-edited, per ADR-0010.
Run with --check to fail when the generated output is stale, which is how continuous
integration enforces that rule.

The generator also runs the contrast audit and refuses to emit a preset that fails
WCAG AA, so an inaccessible palette cannot reach the interface.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from nickland.domain.theme import (  # noqa: E402
    ThemeDefinition,
    audit,
    customisable_tokens,
    load_presets,
)

TOKENS = ROOT / "tokens"
OUTPUT = ROOT / "ui" / "src" / "tokens"
BANNER = "/* GENERATED by tools/generate_tokens.py — do not edit. */"


def flatten(data: dict, prefix: str = "") -> dict[str, str]:
    result: dict[str, str] = {}
    for key, value in data.items():
        if str(key).startswith("$"):
            continue
        name = f"{prefix}-{key}" if prefix else str(key)
        if isinstance(value, dict):
            result.update(flatten(value, name))
        else:
            result[name] = str(value)
    return result


def build_css(primitives: dict[str, str], presets: dict) -> str:
    lines = [BANNER, ""]
    lines.append(":root {")
    for name, value in primitives.items():
        lines.append(f"  --{name}: {value};")
    lines.append("}")
    lines.append("")
    for code, preset in presets.items():
        selector = f'[data-theme="{code}"]'
        lines.append(f"/* {preset.name} — {preset.source} */")
        lines.append(f"{selector} {{")
        for token, value in preset.colour.items():
            lines.append(f"  --colour-{token}: {value};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def build_typescript(primitives: dict[str, str], presets: dict) -> str:
    preset_payload = {
        code: {
            "code": preset.code,
            "name": preset.name,
            "description": preset.description,
            "source": preset.source,
            "recommended": preset.recommended,
            "colour": preset.colour,
        }
        for code, preset in presets.items()
    }
    colour_tokens = sorted(next(iter(presets.values())).colour)
    return "\n".join(
        [
            BANNER,
            "",
            f"export const PRESET_CODES = {json.dumps(sorted(presets))} as const;",
            "export type PresetCode = (typeof PRESET_CODES)[number];",
            "",
            f"export const COLOUR_TOKENS = {json.dumps(colour_tokens, indent=2)} as const;",
            "export type ColourToken = (typeof COLOUR_TOKENS)[number];",
            "",
            "export const CUSTOMISABLE_TOKENS =",
            f"  {json.dumps(sorted(customisable_tokens()), indent=2)} as const;",
            "export type CustomisableToken = (typeof CUSTOMISABLE_TOKENS)[number];",
            "",
            "export interface ThemePreset {",
            "  code: PresetCode;",
            "  name: string;",
            "  description: string;",
            "  source: string;",
            "  colour: Record<ColourToken, string>;",
            "}",
            "",
            "export const PRESETS: Record<PresetCode, ThemePreset> =",
            f"  {json.dumps(preset_payload, indent=2)} as Record<PresetCode, ThemePreset>;",
            "",
            f"export const PRIMITIVES = {json.dumps(primitives, indent=2)} as const;",
            "",
            "/** A colour token as a CSS custom property reference. */",
            "export function colour(token: ColourToken): string {",
            "  return `var(--colour-${token})`;",
            "}",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if output is stale")
    arguments = parser.parse_args()

    primitives = flatten(json.loads((TOKENS / "primitives.json").read_text(encoding="utf-8")))
    presets = load_presets()

    # Refuse to emit a preset that fails the accessibility audit.
    problems: list[str] = []
    for code, preset in presets.items():
        for result in audit(ThemeDefinition(preset=preset)):
            if not result.passes:
                problems.append(f"  {code}: {result.describe()}")
    if problems:
        print("Contrast audit FAILED:", file=sys.stderr)
        print("\n".join(problems), file=sys.stderr)
        return 1

    artefacts = {
        OUTPUT / "tokens.css": build_css(primitives, presets),
        OUTPUT / "index.ts": build_typescript(primitives, presets),
    }

    if arguments.check:
        stale = [
            path.relative_to(ROOT)
            for path, content in artefacts.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print(f"Generated token files are stale: {stale}", file=sys.stderr)
            print("Run: python tools/generate_tokens.py", file=sys.stderr)
            return 1
        print("Token artefacts are current.")
        return 0

    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path, content in artefacts.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")

    audited = sum(len(audit(ThemeDefinition(preset=preset))) for preset in presets.values())
    print(f"Contrast audit passed: {audited} pairings across {len(presets)} presets.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
